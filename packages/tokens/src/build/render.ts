import { accentRamps, ramps } from '../primitives/color.ts';
import { duration, easing } from '../primitives/motion.ts';
import { container, lightShadow, radius, radiusScales, shadow, spacingBase, zIndex } from '../primitives/scale.ts';
import { fontFamily, textRoles, textScales, tracking } from '../primitives/typography.ts';
import { componentTokens } from '../component/index.ts';
import { defaultTheme, themes } from '../semantic/color.ts';
import { cssReference, rampVar } from './resolve.ts';

const HEADER = '/* Generated by `pnpm --filter @focus/tokens build` from packages/tokens/src. Do not edit. */\n';

/** Shadows per theme, emitted as `--elevation-*` so `shadow-*` utilities follow the active theme. */
const shadows: Record<keyof typeof themes, Record<keyof typeof shadow, string>> = { dark: shadow, light: lightShadow };

function block(selector: string, lines: string[]): string {
    return `${selector} {\n${lines.map((line) => `    ${line}`).join('\n')}\n}\n`;
}

/** Framework-agnostic custom properties: primitives, semantic roles per theme, component tokens. */
export function renderVariablesCss(): string {
    const primitives = Object.entries(ramps).flatMap(([ramp, steps]) =>
        Object.entries(steps).map(([step, hex]) => `${rampVar(ramp, step)}: ${hex};`),
    );

    const themeBlocks = Object.entries(themes).map(([name, roles]) => {
        const selector = name === defaultTheme ? `:root,\n[data-theme='${name}']` : `[data-theme='${name}']`;
        return block(selector, [
            `color-scheme: ${name === 'dark' ? 'dark' : 'light'};`,
            ...Object.entries(roles).map(([role, value]) => `--${role}: ${cssReference(value)};`),
            ...Object.entries(shadows[name as keyof typeof themes]).map(
                ([level, value]) => `--elevation-${level}: ${value};`,
            ),
        ]);
    });

    const scales = [
        ...Object.entries(duration).map(([name, ms]) => `--duration-${name}: ${ms}ms;`),
        ...Object.entries(zIndex).map(([name, value]) => `--z-${name}: ${value};`),
        ...Object.entries(componentTokens).map(([name, value]) => `--${name}: ${value};`),
        ...Object.entries(accentRamps).map(([name, steps]) => `--swatch-${name}: ${steps[400]};`),
    ];

    const accents = Object.entries(accentRamps)
        .filter(([name]) => name !== 'green')
        .map(([name, steps]) =>
            block(
                `:root[data-accent='${name}']`,
                Object.entries(steps).map(([step, hex]) => `${rampVar('green', step)}: ${hex};`),
            ),
        );
    const corners = Object.entries(radiusScales)
        .filter(([name]) => name !== 'round')
        .map(([name, sizes]) =>
            block(
                `:root[data-corners='${name}']`,
                Object.entries(sizes).map(([size, value]) => `--radius-${size}: ${value};`),
            ),
        );
    const textSizes = Object.entries(textScales)
        .filter(([name]) => name !== 'default')
        .map(([name, size]) => block(`:root[data-text-size='${name}']`, [`font-size: ${size};`]));

    return [
        HEADER,
        block(':root', ['/* Primitives — never referenced by components */', ...primitives]),
        ...themeBlocks,
        block(':root', scales),
        ...accents,
        ...corners,
        ...textSizes,
    ].join('\n');
}

/**
 * Tailwind v4 theme. Default palettes, type sizes, radii, shadows and easings are cleared,
 * so only system tokens generate utilities — `bg-red-500` or `rounded-xl` simply do not exist.
 */
export function renderTailwindCss(): string {
    const roles = Object.keys(themes[defaultTheme]);

    const theme = [
        '--color-*: initial;',
        '--font-*: initial;',
        '--text-*: initial;',
        '--radius-*: initial;',
        '--shadow-*: initial;',
        '--ease-*: initial;',
        '--inset-shadow-*: initial;',
        '--drop-shadow-*: initial;',
        `--spacing: ${spacingBase};`,
        ...Object.entries(fontFamily).map(([name, value]) => `--font-${name}: ${value};`),
        ...Object.entries(textRoles).flatMap(([role, { size, lineHeight }]) => [
            `--text-${role}: ${size};`,
            `--text-${role}--line-height: ${lineHeight};`,
        ]),
        ...Object.entries(tracking).map(([name, value]) => `--tracking-${name}: ${value};`),
        ...Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value};`),
        ...Object.entries(easing).map(([name, value]) => `--ease-${name}: ${value.css};`),
        ...Object.entries(container).map(([name, value]) => `--container-${name}: ${value};`),
    ];

    const colors = [
        '--color-transparent: transparent;',
        '--color-current: currentColor;',
        ...roles.map((role) => `--color-${role}: var(--${role});`),
        ...Object.keys(shadow).map((level) => `--shadow-${level}: var(--elevation-${level});`),
    ];

    return [HEADER, "@import './variables.css';\n", block('@theme', theme), block('@theme inline', colors)].join('\n');
}
