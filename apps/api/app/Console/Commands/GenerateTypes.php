<?php

namespace App\Console\Commands;

use App\Support\Contract;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Str;

#[Signature('focus:types {--check : Fail instead of writing when the file is out of date} {--path= : Output file}')]
#[Description('Generate the shared TypeScript contract in packages/types from the Laravel enums and limits')]
class GenerateTypes extends Command
{
    public function handle(): int
    {
        $path = $this->option('path') ?: base_path('../../packages/types/src/generated/contract.ts');
        $contents = $this->render();

        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $contents) {
                $this->components->error('packages/types is out of date. Run `php artisan focus:types`.');

                return self::FAILURE;
            }

            $this->components->info('Shared types are up to date.');

            return self::SUCCESS;
        }

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        file_put_contents($path, $contents);
        $this->components->info("Wrote {$path}");

        return self::SUCCESS;
    }

    private function render(): string
    {
        $lines = [
            '// Generated by `php artisan focus:types` from apps/api/app/Support/Contract.php.',
            '// Do not edit by hand — change the Laravel enums or limits and regenerate.',
            '',
        ];

        foreach (Contract::enums() as $type => $values) {
            $constant = Str::of($type)->snake()->upper()->plural()->toString();
            $list = implode(', ', array_map(fn (string $value) => "'{$value}'", $values));
            $lines[] = "export const {$constant} = [{$list}] as const;";
            $lines[] = "export type {$type} = (typeof {$constant})[number];";
            $lines[] = '';
        }

        $lines[] = 'export const LIMITS = '.$this->literal(Contract::limits()).' as const;';

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<string, mixed>  $value
     */
    private function literal(array $value, int $depth = 0): string
    {
        $indent = str_repeat('    ', $depth + 1);
        $entries = array_map(
            fn (string $key, mixed $item) => $indent.$key.': '.(is_array($item) ? $this->literal($item, $depth + 1) : $item).',',
            array_keys($value),
            $value,
        );

        return "{\n".implode("\n", $entries)."\n".str_repeat('    ', $depth).'}';
    }
}
